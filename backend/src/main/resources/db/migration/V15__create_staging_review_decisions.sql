-- #51: staging 검수·공개 등록 연동. V1~V14 는 이미 적용되어 고치지 않는다(제약은 이 파일에서 다시 만든다).
-- 새 FK 에 CASCADE 없음.

-- 수집 revision: 수집 결과 반영으로 내용·수집 상태가 바뀔 때마다 1씩 오른다(StagingIngestService).
-- 검수 승인은 검수자가 본 revision 과 같을 때만 적용한다(검수 중 재수집된 내용을 모르게 승인하지 않음).
ALTER TABLE staging_listings ADD COLUMN revision BIGINT NOT NULL DEFAULT 0;
ALTER TABLE staging_listings ADD CONSTRAINT ck_staging_revision CHECK (revision >= 0);

-- 검수 결정 기록(추가만). 기존 작품 연결·새 작품 등록은 staging 한 행에 한 번만 있다(반복·동시 승인 방지)
CREATE TABLE staging_review_decisions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staging_id       BIGINT       NOT NULL,
    decision         VARCHAR(20)  NOT NULL,
    staging_revision BIGINT       NOT NULL,
    from_status      VARCHAR(20)  NOT NULL,
    to_status        VARCHAR(20)  NOT NULL,
    work_id          BIGINT,
    listing_id       BIGINT,
    candidates       JSONB        NOT NULL DEFAULT '[]',
    reason           VARCHAR(500) NOT NULL,
    decided_by       BIGINT       NOT NULL,
    decided_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_srd_staging FOREIGN KEY (staging_id) REFERENCES staging_listings (id),
    CONSTRAINT fk_srd_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_srd_listing FOREIGN KEY (listing_id) REFERENCES work_platform_listings (id),
    CONSTRAINT fk_srd_decided_by FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_srd_decision CHECK (decision IN ('LINK_EXISTING', 'CREATE_WORK', 'HOLD', 'REJECT')),
    CONSTRAINT ck_srd_target CHECK ((decision IN ('LINK_EXISTING', 'CREATE_WORK'))
        = (work_id IS NOT NULL AND listing_id IS NOT NULL)),
    CONSTRAINT ck_srd_status CHECK (from_status IN ('NEW', 'CANDIDATES', 'IN_REVIEW', 'LINKED', 'NEW_WORK', 'REJECTED',
        'ON_HOLD', 'MERGED_ALIAS') AND to_status IN ('LINKED', 'NEW_WORK', 'REJECTED', 'ON_HOLD')),
    CONSTRAINT ck_srd_revision CHECK (staging_revision >= 0),
    CONSTRAINT ck_srd_reason CHECK (btrim(reason) <> ''),
    CONSTRAINT ck_srd_candidates CHECK (jsonb_typeof(candidates) = 'array')
);
CREATE UNIQUE INDEX uk_srd_final ON staging_review_decisions (staging_id)
    WHERE decision IN ('LINK_EXISTING', 'CREATE_WORK');
CREATE INDEX idx_srd_staging ON staging_review_decisions (staging_id, id DESC);

CREATE FUNCTION staging_review_decisions_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'staging_review_decisions is append-only';
END;
$$;
CREATE TRIGGER trg_srd_append_only BEFORE UPDATE OR DELETE ON staging_review_decisions
    FOR EACH ROW EXECUTE FUNCTION staging_review_decisions_append_only();

