-- #45: 검수 후보, 표지 단계, 누락 현황 표 (docs/work-collection-design.md §8.3)
-- 이 이슈는 표와 제약만 만든다. 후보 생성·판정(#51), 표지 다운로드·표시(#55), 누락 집계(#52)는 각 이슈에서 구현한다.
-- 새 FK 에 CASCADE 없음.

CREATE TABLE staging_match_candidates (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staging_id       BIGINT       NOT NULL,
    work_id          BIGINT,
    other_staging_id BIGINT,
    score            NUMERIC(5, 2) NOT NULL,
    reasons          JSONB        NOT NULL,
    warnings         JSONB        NOT NULL DEFAULT '[]',
    status           VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    decided_by       BIGINT,
    decided_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_smc_staging FOREIGN KEY (staging_id) REFERENCES staging_listings (id),
    CONSTRAINT fk_smc_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_smc_other FOREIGN KEY (other_staging_id) REFERENCES staging_listings (id),
    CONSTRAINT fk_smc_decided_by FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_smc_target CHECK ((work_id IS NULL) <> (other_staging_id IS NULL)),
    CONSTRAINT ck_smc_self CHECK (other_staging_id IS NULL OR other_staging_id <> staging_id),
    CONSTRAINT ck_smc_status CHECK (status IN ('OPEN', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_smc_decided CHECK ((status = 'OPEN') = (decided_by IS NULL) AND (decided_by IS NULL) = (decided_at IS NULL)),
    CONSTRAINT ck_smc_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_smc_json CHECK (jsonb_typeof(reasons) = 'array' AND jsonb_typeof(warnings) = 'array')
);
-- 후보 생성을 다시 돌려도 행이 늘지 않게(점수·근거는 갱신)
CREATE UNIQUE INDEX uk_smc_work ON staging_match_candidates (staging_id, work_id) WHERE work_id IS NOT NULL;
CREATE UNIQUE INDEX uk_smc_pair ON staging_match_candidates
    (LEAST(staging_id, other_staging_id), GREATEST(staging_id, other_staging_id)) WHERE other_staging_id IS NOT NULL;

-- 표지: 1단계(URL)는 staging_listings.cover_url 에만 있다. 검수로 연결이 생기면 cover_assets 행을 만든다
CREATE TABLE cover_assets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id  BIGINT        NOT NULL,
    source_url  VARCHAR(1000) NOT NULL,
    stage       VARCHAR(20)   NOT NULL DEFAULT 'URL_COLLECTED',
    storage_key VARCHAR(300),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_cover_assets_listing FOREIGN KEY (listing_id) REFERENCES work_platform_listings (id),
    CONSTRAINT uk_cover_assets UNIQUE (listing_id, source_url),
    CONSTRAINT ck_cover_stage CHECK (stage IN ('URL_COLLECTED', 'DOWNLOAD_APPROVED', 'DOWNLOADED', 'DISPLAY_APPROVED', 'WITHDRAWN')),
    CONSTRAINT ck_cover_storage CHECK (stage <> 'DOWNLOADED' OR storage_key IS NOT NULL),
    CONSTRAINT ck_cover_url CHECK (source_url LIKE 'https://%')
);

-- 단계마다 승인자·근거·시각을 남긴다(덮어쓰지 않음). 권리 근거는 있으면 기록(필수 아님)
CREATE TABLE cover_asset_stage_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cover_id     BIGINT        NOT NULL,
    from_stage   VARCHAR(20),
    to_stage     VARCHAR(20)   NOT NULL,
    rights_basis VARCHAR(30),
    rights_note  VARCHAR(1000),
    approved_by  BIGINT        NOT NULL,
    approved_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_cover_hist_cover FOREIGN KEY (cover_id) REFERENCES cover_assets (id),
    CONSTRAINT fk_cover_hist_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT ck_cover_hist_stages CHECK ((from_stage IS NULL OR from_stage IN
        ('URL_COLLECTED', 'DOWNLOAD_APPROVED', 'DOWNLOADED', 'DISPLAY_APPROVED', 'WITHDRAWN'))
        AND to_stage IN ('URL_COLLECTED', 'DOWNLOAD_APPROVED', 'DOWNLOADED', 'DISPLAY_APPROVED', 'WITHDRAWN')
        AND (from_stage IS NULL OR from_stage <> to_stage)),
    CONSTRAINT ck_cover_hist_rights CHECK (rights_basis IS NULL OR rights_basis IN ('PARTNERSHIP', 'WRITTEN_PERMISSION', 'LICENSE'))
);

CREATE TABLE platform_coverage_snapshots (
    platform_code VARCHAR(30) NOT NULL,
    taken_on      DATE        NOT NULL,
    metrics       JSONB       NOT NULL,
    status        VARCHAR(30) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_platform_coverage PRIMARY KEY (platform_code, taken_on),
    CONSTRAINT fk_coverage_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT ck_coverage_status CHECK (status IN ('NOT_STARTED', 'BLOCKED', 'PARTIAL', 'COMPLETE_ACCESSIBLE', 'NOT_APPLICABLE')),
    CONSTRAINT ck_coverage_metrics CHECK (jsonb_typeof(metrics) = 'object')
);
