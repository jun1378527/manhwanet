-- #40: 작품·작가 외부 ID, 작품 공식 링크, 필드별 근거, 관리 변경 기록
-- docs/work-platform-admin-spec.md §3.3·§5.4·§5.6
-- 원칙
--   * 작품·작가 FK 에 CASCADE 를 두지 않는다(삭제 경로가 없고, 실수로 지울 때 함께 사라지지 않게).
--   * 행을 지우지 않고 상태로 비활성화한다. 변경 기록은 추가만 할 수 있다(UPDATE·DELETE 거절 트리거).
--   * 외부 ID 는 같은 출처에서 한 대상에만 연결한다. INVALID(잘못 연결)로 바꾼 행은 자리를 비워 올바른 대상에 다시 연결할 수 있다.
--   * URL 은 형식만 저장 전에 검사하고 서버가 가져오지 않는다.

-- ---------- 작품 외부 ID ----------
CREATE TABLE work_external_ids (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id     BIGINT       NOT NULL,
    source      VARCHAR(20)  NOT NULL,
    external_id VARCHAR(100) NOT NULL,
    source_url  VARCHAR(500),
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    verified_at TIMESTAMPTZ  NOT NULL,
    verified_by BIGINT       NOT NULL,
    note        VARCHAR(300),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_work_external_ids_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_work_external_ids_verified_by FOREIGN KEY (verified_by) REFERENCES users (id),
    CONSTRAINT ck_work_external_ids_source CHECK (source IN ('WIKIDATA', 'MADB', 'NDL', 'KMAS')),
    CONSTRAINT ck_work_external_ids_external_id CHECK (external_id ~ '^[!-~]{1,100}$'),
    CONSTRAINT ck_work_external_ids_wikidata CHECK (source <> 'WIKIDATA' OR external_id ~ '^Q[1-9][0-9]{0,11}$'),
    CONSTRAINT ck_work_external_ids_url CHECK (source_url IS NULL OR source_url LIKE 'https://%'),
    CONSTRAINT ck_work_external_ids_status CHECK (status IN ('ACTIVE', 'SUPERSEDED', 'INVALID')),
    CONSTRAINT ck_work_external_ids_note CHECK (note IS NULL OR btrim(note) <> '')
);
CREATE UNIQUE INDEX uk_work_external_ids_source_id ON work_external_ids (source, external_id) WHERE status <> 'INVALID';
CREATE INDEX idx_work_external_ids_work ON work_external_ids (work_id, id);

-- ---------- 작가 외부 ID ----------
