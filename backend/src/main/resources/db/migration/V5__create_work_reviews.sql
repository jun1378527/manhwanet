-- 작품 리뷰 (docs/review-design-draft.md)
-- 사용자·작품당 리뷰 1개. 별점(work_ratings)과 독립이며 서로 참조하지 않는다.
-- 쓰기는 애플리케이션의 INSERT ... ON CONFLICT DO NOTHING / SELECT ... FOR UPDATE + UPDATE / DELETE SQL로만 하며 시각도 그 SQL이 정한다.
-- body 는 애플리케이션이 정규화(CRLF·CR → LF, 제어 문자 거절, 앞뒤 공백 제거)한 값만 저장한다.
--   최소 10자는 애플리케이션 정책이고, DB는 1~2,000자(코드 포인트)와 공백만이 아님을 최후의 안전장치로 보장한다.
--   btrim 은 U+0020 만 제거하므로 유니코드 공백 처리는 애플리케이션 책임이다.
-- version 은 수정할 때마다 1 증가한다. 수정·삭제는 id 와 version 이 모두 일치할 때만 한다.
-- 제약 이름은 애플리케이션(FK 위반 → 404 변환, ON CONFLICT 대상)과 테스트가 참조하므로 변경 시 함께 수정한다.
CREATE TABLE work_reviews (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL,
    work_id          BIGINT      NOT NULL,
    body             TEXT        NOT NULL,
    contains_spoiler BOOLEAN     NOT NULL,
    version          BIGINT      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 회원 탈퇴 정책 전까지 리뷰가 있는 사용자 삭제를 막는다.
    CONSTRAINT fk_work_reviews_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_work_reviews_work FOREIGN KEY (work_id) REFERENCES works (id) ON DELETE CASCADE,
    CONSTRAINT uk_work_reviews_user_work UNIQUE (user_id, work_id),
    CONSTRAINT ck_work_reviews_body_length CHECK (char_length(body) BETWEEN 1 AND 2000),
    CONSTRAINT ck_work_reviews_body_not_blank CHECK (btrim(body) <> ''),
    CONSTRAINT ck_work_reviews_version CHECK (version >= 0),
    CONSTRAINT ck_work_reviews_updated_at CHECK (updated_at >= created_at)
);

-- 작품별 공개 목록(created_at DESC, id DESC)과 작품별 COUNT
CREATE INDEX idx_work_reviews_work_created ON work_reviews (work_id, created_at DESC, id DESC);
