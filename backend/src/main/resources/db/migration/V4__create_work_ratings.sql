-- 작품 별점 (docs/rating-design-draft.md)
-- score_half: 반 점 단위 정수. 1 = 0.5점, 10 = 5.0점. 0점은 없고, 평가하지 않음은 행이 없는 상태다.
-- 쓰기는 애플리케이션의 INSERT ... ON CONFLICT / DELETE SQL로만 하며 시각도 그 SQL이 정한다.
-- 제약 이름은 애플리케이션(FK 위반 → 404 변환, upsert 충돌 대상)과 테스트가 참조하므로 변경 시 함께 수정한다.
CREATE TABLE work_ratings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    work_id    BIGINT      NOT NULL,
    score_half SMALLINT    NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- 회원 탈퇴 정책 전까지 별점이 있는 사용자 삭제를 막는다.
    CONSTRAINT fk_work_ratings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_work_ratings_work FOREIGN KEY (work_id) REFERENCES works (id) ON DELETE CASCADE,
    CONSTRAINT ck_work_ratings_score_half CHECK (score_half BETWEEN 1 AND 10),
    CONSTRAINT ck_work_ratings_updated_at CHECK (updated_at >= created_at),
    CONSTRAINT uk_work_ratings_user_work UNIQUE (user_id, work_id)
);

-- 작품별 COUNT / SUM 집계를 인덱스만으로 읽기 위한 커버링 인덱스
CREATE INDEX idx_work_ratings_work_id ON work_ratings (work_id) INCLUDE (score_half);
