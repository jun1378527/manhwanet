-- 제약 이름은 애플리케이션(중복 제약 → 409 변환)과 테스트가 참조하므로 변경 시 함께 수정한다.

CREATE TABLE creators (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    original_name VARCHAR(100),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_creators_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_creators_original_name_not_blank CHECK (original_name IS NULL OR btrim(original_name) <> '')
);

CREATE INDEX idx_creators_created_at_id ON creators (created_at DESC, id DESC);

CREATE TABLE works (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_format    VARCHAR(20) NOT NULL,
    origin_country VARCHAR(2),
    description    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_works_work_format CHECK (work_format IN ('WEBTOON', 'PAGE_COMIC')),
    CONSTRAINT ck_works_origin_country CHECK (origin_country IS NULL OR origin_country ~ '^[A-Z]{2}$')
);

CREATE INDEX idx_works_created_at_id ON works (created_at DESC, id DESC);

-- language_code: BCP 47 태그. RFC 5646 4.4.1 권고에 따라 35자까지 저장한다.
CREATE TABLE work_titles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id       BIGINT       NOT NULL,
    title         VARCHAR(255) NOT NULL,
    language_code VARCHAR(35)  NOT NULL,
    is_primary    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_work_titles_work FOREIGN KEY (work_id) REFERENCES works (id) ON DELETE CASCADE,
    CONSTRAINT ck_work_titles_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_work_titles_language_code_not_blank CHECK (btrim(language_code) <> ''),
    CONSTRAINT uk_work_titles_work_language_title UNIQUE (work_id, language_code, title)
);

-- 대표 제목을 작품당 "최대 1개"로 제한한다. "정확히 1개"는 애플리케이션이 보장한다.
CREATE UNIQUE INDEX uk_work_titles_primary_per_work ON work_titles (work_id) WHERE is_primary;

CREATE TABLE work_creators (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id    BIGINT      NOT NULL,
    creator_id BIGINT      NOT NULL,
    role       VARCHAR(20) NOT NULL,
    CONSTRAINT fk_work_creators_work FOREIGN KEY (work_id) REFERENCES works (id) ON DELETE CASCADE,
    CONSTRAINT fk_work_creators_creator FOREIGN KEY (creator_id) REFERENCES creators (id) ON DELETE RESTRICT,
    CONSTRAINT ck_work_creators_role CHECK (role IN ('STORY', 'ART', 'ORIGINAL_STORY')),
    CONSTRAINT uk_work_creators_work_creator_role UNIQUE (work_id, creator_id, role)
);

CREATE INDEX idx_work_creators_creator_id ON work_creators (creator_id);
