-- 회원 (docs/auth-design-draft.md)
-- email 은 애플리케이션이 앞뒤 공백 제거 + Locale.ROOT 소문자로 정규화한 값만 저장한다.
-- 관리자 계정이나 기본 비밀번호는 마이그레이션에 넣지 않는다. (관리자는 별도 생성 명령으로 만든다)
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname      VARCHAR(30)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT ck_users_nickname_not_blank CHECK (btrim(nickname) <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);
