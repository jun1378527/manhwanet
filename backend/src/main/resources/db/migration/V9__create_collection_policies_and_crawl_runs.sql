-- #45: 플랫폼 수집 설정과 수집 실행 기록 (docs/work-collection-design.md §7·§8.1)
-- 원칙
--   * 새 FK 에 CASCADE 를 두지 않는다. 적용된 V1~V8 은 고치지 않는다.
--   * 수집 설정의 기본값은 DISABLED 이다. 기본값이 아닌 설정은 바꾼 관리자·시각을 남긴다.
--     외부 허락 문서(basis_kind)는 선택이며 실행 조건이 아니다(2026-10-12 사용자 결정, 설계 §16.1 D-11).
--   * 플랫폼마다 활성 실행(RUNNING·PAUSED·STOP_REQUESTED·BLOCKED)은 하나뿐이다.
--   * 작업은 실행 안에서 (종류, URL 해시)로 한 번만 만든다. 실행이 끊겨도 큐가 DB 에 남는다.

-- ---------- 플랫폼 수집 설정 ----------
CREATE TABLE platform_collection_policies (
    platform_code     VARCHAR(30)   PRIMARY KEY,
    collection_policy VARCHAR(20)   NOT NULL DEFAULT 'DISABLED',
    synopsis_policy   VARCHAR(20)   NOT NULL DEFAULT 'COLLECT_PRIVATE',
    cover_policy      VARCHAR(20)   NOT NULL DEFAULT 'URL_ONLY',
    note              VARCHAR(1000),
    basis_kind        VARCHAR(30),
    basis_note        VARCHAR(1000),
    decided_by        BIGINT,
    decided_at        TIMESTAMPTZ,
    rate_interval_ms  INTEGER       NOT NULL DEFAULT 5000,
    daily_request_cap INTEGER       NOT NULL DEFAULT 15000,
    version           BIGINT        NOT NULL DEFAULT 0,
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_pcp_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT fk_pcp_decided_by FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_pcp_collection CHECK (collection_policy IN ('DISABLED', 'PROBE', 'ENABLED')),
    CONSTRAINT ck_pcp_synopsis CHECK (synopsis_policy IN ('NOT_COLLECTED', 'COLLECT_PRIVATE', 'DISPLAY')),
    CONSTRAINT ck_pcp_cover CHECK (cover_policy IN ('URL_ONLY', 'DOWNLOAD', 'DISPLAY')),
    CONSTRAINT ck_pcp_basis_kind CHECK (basis_kind IS NULL OR basis_kind IN
        ('PARTNERSHIP', 'WRITTEN_PERMISSION', 'LEGAL_REVIEW', 'PLATFORM_REPLY')),
    CONSTRAINT ck_pcp_basis_note CHECK (basis_note IS NULL OR basis_kind IS NOT NULL),
    -- 기본값이 아닌 설정은 누가 언제 바꿨는지 남긴다(외부 허락 문서는 필수 아님)
    CONSTRAINT ck_pcp_decided CHECK (
        (collection_policy = 'DISABLED' AND synopsis_policy = 'COLLECT_PRIVATE' AND cover_policy = 'URL_ONLY')
        OR (decided_by IS NOT NULL AND decided_at IS NOT NULL)),
    CONSTRAINT ck_pcp_decided_pair CHECK ((decided_by IS NULL) = (decided_at IS NULL)),
    CONSTRAINT ck_pcp_rate CHECK (rate_interval_ms BETWEEN 1000 AND 3600000 AND daily_request_cap BETWEEN 1 AND 1000000),
    CONSTRAINT ck_pcp_texts CHECK ((note IS NULL OR btrim(note) <> '') AND (basis_note IS NULL OR btrim(basis_note) <> '')),
    CONSTRAINT ck_pcp_version CHECK (version >= 0)
);

-- 10개 플랫폼 모두 DISABLED 로 시작한다(값을 임의로 켜지 않음)
INSERT INTO platform_collection_policies (platform_code) SELECT code FROM platforms ORDER BY code;

-- ---------- 수집 실행 ----------
CREATE TABLE crawl_runs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_code     VARCHAR(30)  NOT NULL,
    run_kind          VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL DEFAULT 'RUNNING',
    stop_reason       VARCHAR(30),
    robots_sha256     CHAR(64),
    adapter_version   VARCHAR(30)  NOT NULL,
    lease_owner       VARCHAR(100),
    lease_until       TIMESTAMPTZ,
    started_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    stop_requested_at TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ,
    stats             JSONB        NOT NULL DEFAULT '{}',
    CONSTRAINT fk_crawl_runs_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT ck_crawl_runs_kind CHECK (run_kind IN ('PROBE', 'FULL', 'INCREMENTAL', 'RECHECK')),
    CONSTRAINT ck_crawl_runs_status CHECK (status IN
        ('RUNNING', 'PAUSED', 'STOP_REQUESTED', 'BLOCKED', 'STOPPED', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_crawl_runs_stop_reason CHECK (stop_reason IS NULL OR stop_reason IN
        ('BLOCKED_RATE', 'BLOCKED_ACCESS', 'ROBOTS_UNAVAILABLE', 'CIRCUIT_OPEN', 'OPERATOR_STOP', 'ERROR')),
    CONSTRAINT ck_crawl_runs_blocked CHECK (status <> 'BLOCKED' OR stop_reason IS NOT NULL),
    CONSTRAINT ck_crawl_runs_finished CHECK ((status IN ('STOPPED', 'COMPLETED', 'FAILED')) = (finished_at IS NOT NULL)),
    -- 끝난 실행은 잠금을 쥐지 않는다
    CONSTRAINT ck_crawl_runs_lease CHECK ((lease_owner IS NULL) = (lease_until IS NULL)
        AND (finished_at IS NULL OR lease_owner IS NULL)),
    CONSTRAINT ck_crawl_runs_robots CHECK (robots_sha256 IS NULL OR robots_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_crawl_runs_texts CHECK (btrim(adapter_version) <> '' AND (lease_owner IS NULL OR btrim(lease_owner) <> '')),
    CONSTRAINT ck_crawl_runs_stats CHECK (jsonb_typeof(stats) = 'object')
);
-- 플랫폼당 활성 실행은 하나. 잠금이 만료되면 새 행을 만들지 않고 이 행의 잠금을 넘겨받는다(§7.4)
CREATE UNIQUE INDEX uk_crawl_runs_active ON crawl_runs (platform_code)
    WHERE status IN ('RUNNING', 'PAUSED', 'STOP_REQUESTED', 'BLOCKED');
CREATE INDEX idx_crawl_runs_platform ON crawl_runs (platform_code, id DESC);

-- ---------- 작업 큐 ----------
CREATE TABLE crawl_tasks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           BIGINT        NOT NULL,
    task_kind        VARCHAR(20)   NOT NULL,
    url              VARCHAR(1000) NOT NULL,
    url_hash         CHAR(64)      NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    attempts         SMALLINT      NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    last_http_status SMALLINT,
    last_error       VARCHAR(30),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_crawl_tasks_run FOREIGN KEY (run_id) REFERENCES crawl_runs (id),
    CONSTRAINT uk_crawl_tasks UNIQUE (run_id, task_kind, url_hash),
    CONSTRAINT ck_crawl_tasks_kind CHECK (task_kind IN ('ROBOTS', 'SITEMAP', 'LIST', 'DETAIL')),
    CONSTRAINT ck_crawl_tasks_status CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED', 'SKIPPED')),
    CONSTRAINT ck_crawl_tasks_error CHECK (last_error IS NULL OR last_error IN
        ('TIMEOUT', 'CONNECTION', 'HTTP_5XX', 'RATE_LIMITED', 'BLOCKED_ACCESS', 'GATED', 'NOT_FOUND', 'PARSE_FAILED',
         'SKIPPED_ROBOTS', 'SKIPPED_ADULT', 'OPERATOR_STOP')),
    CONSTRAINT ck_crawl_tasks_url CHECK (url LIKE 'https://%'),
    CONSTRAINT ck_crawl_tasks_hash CHECK (url_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_crawl_tasks_attempts CHECK (attempts BETWEEN 0 AND 100),
    CONSTRAINT ck_crawl_tasks_http CHECK (last_http_status IS NULL OR last_http_status BETWEEN 100 AND 599)
);
CREATE INDEX idx_crawl_tasks_queue ON crawl_tasks (run_id, status, next_attempt_at, id);

-- ---------- 실패 표본(파싱 실패 원문) ----------
-- 실행당 최대 200건(서비스가 지킴), expires_at 이 지나면 정리 작업이 지운다(행 삭제는 이 표만 허용).
CREATE TABLE crawl_failure_samples (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT      NOT NULL,
    http_status SMALLINT,
    error       VARCHAR(30) NOT NULL,
    body_gzip   BYTEA,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '30 days'),
    CONSTRAINT fk_crawl_failure_samples_task FOREIGN KEY (task_id) REFERENCES crawl_tasks (id),
    CONSTRAINT ck_crawl_failure_samples_size CHECK (body_gzip IS NULL OR octet_length(body_gzip) <= 1048576),
    CONSTRAINT ck_crawl_failure_samples_http CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    CONSTRAINT ck_crawl_failure_samples_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_crawl_failure_samples_task ON crawl_failure_samples (task_id);
CREATE INDEX idx_crawl_failure_samples_expiry ON crawl_failure_samples (expires_at);

-- ---------- 관리 변경 기록 대상 추가 ----------
-- V8 의 CHECK 를 이 마이그레이션에서 넓힌다(V8 파일은 고치지 않음). 수집 설정 변경과 실행 중단 요청을 기록한다.
ALTER TABLE admin_change_log DROP CONSTRAINT ck_change_log_entity_type;
ALTER TABLE admin_change_log ADD CONSTRAINT ck_change_log_entity_type CHECK (entity_type IN ('WORK', 'CREATOR',
    'LISTING', 'PLATFORM', 'WORK_EXTERNAL_ID', 'CREATOR_EXTERNAL_ID', 'WORK_LINK', 'FIELD_SOURCE',
    'COLLECTION_POLICY', 'CRAWL_RUN'));
