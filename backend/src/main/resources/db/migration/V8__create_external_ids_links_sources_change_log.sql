    CONSTRAINT fk_creator_external_ids_creator FOREIGN KEY (creator_id) REFERENCES creators (id),
    CONSTRAINT fk_creator_external_ids_verified_by FOREIGN KEY (verified_by) REFERENCES users (id),
    CONSTRAINT ck_creator_external_ids_source CHECK (source IN ('WIKIDATA', 'MADB', 'NDL', 'KMAS')),
    CONSTRAINT ck_creator_external_ids_external_id CHECK (external_id ~ '^[!-~]{1,100}$'),
    CONSTRAINT ck_creator_external_ids_wikidata CHECK (source <> 'WIKIDATA' OR external_id ~ '^Q[1-9][0-9]{0,11}$'),
    CONSTRAINT ck_creator_external_ids_url CHECK (source_url IS NULL OR source_url LIKE 'https://%'),
    CONSTRAINT ck_creator_external_ids_status CHECK (status IN ('ACTIVE', 'SUPERSEDED', 'INVALID')),
    CONSTRAINT ck_creator_external_ids_note CHECK (note IS NULL OR btrim(note) <> '')
);
CREATE UNIQUE INDEX uk_creator_external_ids_source_id ON creator_external_ids (source, external_id) WHERE status <> 'INVALID';
CREATE INDEX idx_creator_external_ids_creator ON creator_external_ids (creator_id, id);

-- ---------- 작품 공식 링크(플랫폼 연결이 아닌 출판사·공식 사이트) ----------
CREATE TABLE work_links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id       BIGINT       NOT NULL,
    link_type     VARCHAR(20)  NOT NULL,
    url           VARCHAR(500) NOT NULL,
    language_code VARCHAR(35)  NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    verified_at   TIMESTAMPTZ  NOT NULL,
    verified_by   BIGINT       NOT NULL,
    note          VARCHAR(300),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_work_links_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_work_links_verified_by FOREIGN KEY (verified_by) REFERENCES users (id),
    CONSTRAINT uk_work_links_work_url UNIQUE (work_id, url),
    CONSTRAINT ck_work_links_type CHECK (link_type IN ('PUBLISHER', 'OFFICIAL_SITE')),
    CONSTRAINT ck_work_links_url CHECK (url LIKE 'https://%'),
    CONSTRAINT ck_work_links_language CHECK (btrim(language_code) <> ''),
    CONSTRAINT ck_work_links_status CHECK (status IN ('ACTIVE', 'BROKEN', 'REMOVED')),
    CONSTRAINT ck_work_links_note CHECK (note IS NULL OR btrim(note) <> '')
);

-- ---------- 필드별 근거 ----------
-- field 는 근거를 댄 작품 값. LISTING 근거는 같은 작품의 연결을 가리킨다(복합 FK).
-- 제목·크레딧 행은 수정 때 다시 만들어 ID 가 바뀌므로 target_ref 는 사람이 읽는 값 설명(예: 'ko:유미의 세포들')으로 둔다.
CREATE TABLE work_field_sources (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id     BIGINT       NOT NULL,
    field       VARCHAR(20)  NOT NULL,
    listing_id  BIGINT,
    target_ref  VARCHAR(200),
    source_type VARCHAR(30)  NOT NULL,
    source_ref  VARCHAR(500),
    source_url  VARCHAR(500),
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    verified_at TIMESTAMPTZ  NOT NULL,
    verified_by BIGINT       NOT NULL,
    note        VARCHAR(300),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_field_sources_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_field_sources_listing FOREIGN KEY (listing_id, work_id) REFERENCES work_platform_listings (id, work_id),
    CONSTRAINT fk_field_sources_verified_by FOREIGN KEY (verified_by) REFERENCES users (id),
    CONSTRAINT ck_field_sources_field CHECK (field IN ('TITLE', 'CREDIT', 'WORK_FORMAT', 'ORIGIN_COUNTRY', 'DESCRIPTION', 'LISTING')),
    CONSTRAINT ck_field_sources_listing CHECK ((field = 'LISTING') = (listing_id IS NOT NULL)),
    CONSTRAINT ck_field_sources_source_type CHECK (source_type IN
        ('PLATFORM_PAGE_MANUAL', 'WIKIDATA', 'MADB', 'NDL', 'KMAS', 'PUBLISHER_PAGE', 'STAFF', 'LICENSED')),
    -- 줄거리는 직접 작성(STAFF)하거나 허락받은 글(LICENSED)만
    CONSTRAINT ck_field_sources_description CHECK (field <> 'DESCRIPTION' OR source_type IN ('STAFF', 'LICENSED')),
    -- 직접 작성 외에는 근거 위치(식별자 또는 URL)가 있어야 하고, 허락받은 글은 허락 근거 식별자가 있어야 한다
    CONSTRAINT ck_field_sources_ref CHECK (source_type = 'STAFF' OR source_ref IS NOT NULL OR source_url IS NOT NULL),
    CONSTRAINT ck_field_sources_licensed CHECK (source_type <> 'LICENSED' OR source_ref IS NOT NULL),
    CONSTRAINT ck_field_sources_url CHECK (source_url IS NULL OR source_url LIKE 'https://%'),
    CONSTRAINT ck_field_sources_status CHECK (status IN ('ACTIVE', 'RETRACTED')),
    CONSTRAINT ck_field_sources_texts CHECK ((target_ref IS NULL OR btrim(target_ref) <> '')
        AND (source_ref IS NULL OR btrim(source_ref) <> '') AND (note IS NULL OR btrim(note) <> ''))
);
CREATE INDEX idx_field_sources_work ON work_field_sources (work_id, field, id);
CREATE INDEX idx_field_sources_listing ON work_field_sources (listing_id) WHERE listing_id IS NOT NULL;

-- ---------- 관리 변경 기록 ----------
-- 바뀐 내용과 같은 트랜잭션에 쓴다(함께 커밋·롤백). actor 는 사용자 ID 만 남기고 이메일 등은 넣지 않는다.
CREATE TABLE admin_change_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(30)  NOT NULL,
    entity_id   VARCHAR(50)  NOT NULL,
    action      VARCHAR(20)  NOT NULL,
    work_id     BIGINT,
    creator_id  BIGINT,
    before_json JSONB,
    after_json  JSONB        NOT NULL,
    reason      VARCHAR(500),
    actor_id    BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_change_log_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_change_log_creator FOREIGN KEY (creator_id) REFERENCES creators (id),
    CONSTRAINT fk_change_log_actor FOREIGN KEY (actor_id) REFERENCES users (id),
    CONSTRAINT ck_change_log_entity_type CHECK (entity_type IN ('WORK', 'CREATOR', 'LISTING', 'PLATFORM',
        'WORK_EXTERNAL_ID', 'CREATOR_EXTERNAL_ID', 'WORK_LINK', 'FIELD_SOURCE')),
    CONSTRAINT ck_change_log_entity_id CHECK (btrim(entity_id) <> ''),
    CONSTRAINT ck_change_log_action CHECK (action IN ('CREATE', 'UPDATE', 'STATUS_CHANGE', 'MOVE')),
    -- 생성은 이전 값이 없고, 그 밖의 변경은 이전 값과 사유가 있어야 한다
    CONSTRAINT ck_change_log_before CHECK ((action = 'CREATE') = (before_json IS NULL)),
    CONSTRAINT ck_change_log_reason CHECK (action = 'CREATE' OR reason IS NOT NULL),
    CONSTRAINT ck_change_log_reason_not_blank CHECK (reason IS NULL OR btrim(reason) <> '')
);
CREATE INDEX idx_change_log_entity ON admin_change_log (entity_type, entity_id, id DESC);
CREATE INDEX idx_change_log_work ON admin_change_log (work_id, id DESC) WHERE work_id IS NOT NULL;
CREATE INDEX idx_change_log_creator ON admin_change_log (creator_id, id DESC) WHERE creator_id IS NOT NULL;

CREATE FUNCTION admin_change_log_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'admin_change_log is append-only' USING ERRCODE = 'restrict_violation';
END $$;

CREATE TRIGGER trg_admin_change_log_append_only
    BEFORE UPDATE OR DELETE ON admin_change_log
    FOR EACH ROW EXECUTE FUNCTION admin_change_log_append_only();
