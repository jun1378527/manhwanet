-- 플랫폼 코드 표·운영 상태 이력·작품 플랫폼 연결 (#39, docs/work-platform-admin-spec.md §3.2·§4·§5.3·§5.5)
-- 원칙
--   * 초기 데이터는 플랫폼 코드·표시 이름과 URL 규칙(관찰 근거·확인일 구분)만 넣는다.
--     운영 상태·약관 확인일·기본 ID 단위는 확정 데이터처럼 채우지 않는다(UNKNOWN / UNVERIFIED / NULL).
--     실제 상태는 관리자가 근거와 함께 상태 변경 API 로 기록한다(platform_status_history).
--   * 종료(CLOSED)·통합(MERGING)은 공식 확인(OFFICIAL)일 때만 쓴다. 보도·미확인은 UNKNOWN 상태에 근거(PRESS/UNVERIFIED)를 남긴다.
--   * 작품 연결은 삭제하지 않고 상태(ACTIVE·ENDED·MOVED·UNKNOWN)로 관리한다. 새 FK 에 CASCADE 를 걸지 않는다.
--   * 같은 플랫폼의 같은 외부 작품 ID 는 한 연결만 가진다(UNIQUE). 번호가 같아도 플랫폼이 다르면 다른 식별자다.
-- 제약 이름은 애플리케이션(409 변환)과 테스트가 참조하므로 바꿀 때 함께 수정한다.

CREATE TABLE platforms (
    code                VARCHAR(30)  PRIMARY KEY,
    name                VARCHAR(50)  NOT NULL,
    operator_name       VARCHAR(100),
    status              VARCHAR(20)  NOT NULL DEFAULT 'UNKNOWN',
    status_basis        VARCHAR(20)  NOT NULL DEFAULT 'UNVERIFIED',
    merged_into         VARCHAR(30),
    status_effective_on DATE,
    status_evidence_url VARCHAR(500),
    default_id_scope    VARCHAR(20)  NOT NULL DEFAULT 'UNKNOWN',
    work_url_pattern    VARCHAR(300),
    url_rule_basis      VARCHAR(20)  NOT NULL DEFAULT 'UNVERIFIED',
    url_rule_checked_on DATE,
    terms_checked_on    DATE,
    version             BIGINT       NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_platforms_merged_into FOREIGN KEY (merged_into) REFERENCES platforms (code),
    CONSTRAINT ck_platforms_code CHECK (code ~ '^[A-Z][A-Z0-9_]{1,29}$'),
    CONSTRAINT ck_platforms_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_platforms_operator_not_blank CHECK (operator_name IS NULL OR btrim(operator_name) <> ''),
    CONSTRAINT ck_platforms_status CHECK (status IN ('ACTIVE', 'MERGING', 'CLOSED', 'UNKNOWN')),
    CONSTRAINT ck_platforms_status_basis CHECK (status_basis IN ('OFFICIAL', 'PRESS', 'UNVERIFIED')),
    -- 종료·통합은 공식 확인만. 보도·미확인은 UNKNOWN 으로 남긴다.
    CONSTRAINT ck_platforms_closed_official CHECK (status NOT IN ('MERGING', 'CLOSED') OR status_basis = 'OFFICIAL'),
    CONSTRAINT ck_platforms_merging_target CHECK (status <> 'MERGING' OR merged_into IS NOT NULL),
    CONSTRAINT ck_platforms_merged_state CHECK (merged_into IS NULL OR status IN ('MERGING', 'CLOSED')),
    CONSTRAINT ck_platforms_merged_not_self CHECK (merged_into IS NULL OR merged_into <> code),
    CONSTRAINT ck_platforms_evidence CHECK (status_basis = 'UNVERIFIED' OR status_evidence_url IS NOT NULL),
    CONSTRAINT ck_platforms_default_id_scope CHECK (default_id_scope IN ('SERIES', 'VOLUME_OR_EPISODE', 'EDITION', 'UNKNOWN')),
    CONSTRAINT ck_platforms_url_rule_basis CHECK (url_rule_basis IN ('OBSERVED', 'UNVERIFIED')),
    CONSTRAINT ck_platforms_url_rule_checked CHECK (url_rule_basis = 'UNVERIFIED' OR url_rule_checked_on IS NOT NULL),
    CONSTRAINT ck_platforms_version CHECK (version >= 0)
);

-- 플랫폼별 허용 호스트(소문자 ASCII). 한 호스트는 한 플랫폼에만 속한다.
CREATE TABLE platform_hosts (
    platform_code VARCHAR(30)  NOT NULL,
    host          VARCHAR(253) NOT NULL,
    CONSTRAINT pk_platform_hosts PRIMARY KEY (platform_code, host),
    CONSTRAINT fk_platform_hosts_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT uk_platform_hosts_host UNIQUE (host),
    CONSTRAINT ck_platform_hosts_host CHECK (host ~ '^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$')
);

-- 운영 상태 변경 이력. 상태 변경과 같은 트랜잭션에서 남긴다(되돌리지 않음, 삭제 없음).
CREATE TABLE platform_status_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_code VARCHAR(30)  NOT NULL,
    from_status   VARCHAR(20)  NOT NULL,
    from_basis    VARCHAR(20)  NOT NULL,
    to_status     VARCHAR(20)  NOT NULL,
    to_basis      VARCHAR(20)  NOT NULL,
    merged_into   VARCHAR(30),
    effective_on  DATE,
    evidence_url  VARCHAR(500),
    note          VARCHAR(500),
    changed_by    BIGINT       NOT NULL,
    changed_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_platform_status_history_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT fk_platform_status_history_merged_into FOREIGN KEY (merged_into) REFERENCES platforms (code),
    CONSTRAINT fk_platform_status_history_user FOREIGN KEY (changed_by) REFERENCES users (id),
    CONSTRAINT ck_psh_from_status CHECK (from_status IN ('ACTIVE', 'MERGING', 'CLOSED', 'UNKNOWN')),
    CONSTRAINT ck_psh_to_status CHECK (to_status IN ('ACTIVE', 'MERGING', 'CLOSED', 'UNKNOWN')),
    CONSTRAINT ck_psh_from_basis CHECK (from_basis IN ('OFFICIAL', 'PRESS', 'UNVERIFIED')),
    CONSTRAINT ck_psh_to_basis CHECK (to_basis IN ('OFFICIAL', 'PRESS', 'UNVERIFIED')),
    CONSTRAINT ck_psh_closed_official CHECK (to_status NOT IN ('MERGING', 'CLOSED') OR to_basis = 'OFFICIAL'),
    CONSTRAINT ck_psh_evidence CHECK (to_basis = 'UNVERIFIED' OR evidence_url IS NOT NULL),
    CONSTRAINT ck_psh_merged_not_self CHECK (merged_into IS NULL OR merged_into <> platform_code),
    CONSTRAINT ck_psh_merging_target CHECK (to_status <> 'MERGING' OR merged_into IS NOT NULL)
);

CREATE INDEX idx_platform_status_history_platform ON platform_status_history (platform_code, changed_at DESC, id DESC);

-- 작품 플랫폼 연결. 하나의 작품에 여러 연결을 둘 수 있다.
CREATE TABLE work_platform_listings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id             BIGINT       NOT NULL,
    platform_code       VARCHAR(30)  NOT NULL,
    platform_work_id    VARCHAR(100) NOT NULL,
    id_scope            VARCHAR(20)  NOT NULL,
    url                 VARCHAR(500) NOT NULL,
    listing_kind        VARCHAR(20)  NOT NULL,
    language_code       VARCHAR(35)  NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    moved_to_listing_id BIGINT,
    age_rating_raw      VARCHAR(50),
    age_class           VARCHAR(10)  NOT NULL DEFAULT 'UNKNOWN',
    first_verified_at   TIMESTAMPTZ  NOT NULL,
    last_verified_at    TIMESTAMPTZ  NOT NULL,
    verified_by         BIGINT       NOT NULL,
    note                VARCHAR(500),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_listings_work FOREIGN KEY (work_id) REFERENCES works (id),
    CONSTRAINT fk_listings_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    -- 이전 대상은 같은 작품의 연결이어야 한다(복합 FK, MATCH SIMPLE: moved_to 가 NULL 이면 검사하지 않음)
    CONSTRAINT uk_listings_id_work UNIQUE (id, work_id),
    CONSTRAINT fk_listings_moved_to FOREIGN KEY (moved_to_listing_id, work_id) REFERENCES work_platform_listings (id, work_id),
    CONSTRAINT fk_listings_verified_by FOREIGN KEY (verified_by) REFERENCES users (id),
    CONSTRAINT uk_listings_platform_work UNIQUE (platform_code, platform_work_id),
    -- 외부 ID 는 공백·제어문자·비 ASCII 없는 보이는 ASCII 1~100자(앱 PlatformUrls.isValidWorkId 와 같음)
    CONSTRAINT ck_listings_platform_work_id CHECK (platform_work_id ~ '^[!-~]+$'),
    CONSTRAINT ck_listings_scope CHECK (id_scope IN ('SERIES', 'VOLUME_OR_EPISODE', 'EDITION', 'UNKNOWN')),
    CONSTRAINT ck_listings_kind CHECK (listing_kind IN ('MAIN', 'SEASON', 'EDITION', 'TRANSLATION')),
    CONSTRAINT ck_listings_language_not_blank CHECK (btrim(language_code) <> ''),
    CONSTRAINT ck_listings_url CHECK (url LIKE 'https://%'),
    CONSTRAINT ck_listings_status CHECK (status IN ('ACTIVE', 'ENDED', 'MOVED', 'UNKNOWN')),
    CONSTRAINT ck_listings_moved CHECK ((status = 'MOVED') = (moved_to_listing_id IS NOT NULL)),
    CONSTRAINT ck_listings_moved_not_self CHECK (moved_to_listing_id IS NULL OR moved_to_listing_id <> id),
    CONSTRAINT ck_listings_age_class CHECK (age_class IN ('GENERAL', 'ADULT', 'UNKNOWN')),
    CONSTRAINT ck_listings_age_raw_not_blank CHECK (age_rating_raw IS NULL OR btrim(age_rating_raw) <> ''),
    CONSTRAINT ck_listings_note_not_blank CHECK (note IS NULL OR btrim(note) <> ''),
    CONSTRAINT ck_listings_verified CHECK (last_verified_at >= first_verified_at)
);

CREATE INDEX idx_listings_work ON work_platform_listings (work_id, id);
CREATE INDEX idx_listings_moved_to ON work_platform_listings (moved_to_listing_id) WHERE moved_to_listing_id IS NOT NULL;

