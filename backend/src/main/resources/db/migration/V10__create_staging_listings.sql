-- #45: 수집 결과 staging (docs/work-collection-design.md §6·§7.4·§8.2)
-- 원칙
--   * 수집 결과는 여기에만 쌓고 공개 작품(works)·연결(work_platform_listings)로 자동 등록하지 않는다(검수·등록은 #51).
--   * 식별 키는 (platform_code, platform_work_id). 다시 수집해도 행이 늘지 않는다. 같은 번호라도 플랫폼이 다르면 다른 행이다.
--   * 원래 등급 표기와 신호를 보존한다. 명시적 신호가 없거나 충돌하면 UNKNOWN 이며 GENERAL 로 바꾸지 않는다.
--   * 내용이나 수집 상태가 바뀌면 바뀐 필드의 이전·이후 값을 staging 갱신과 같은 트랜잭션에 남긴다(실행당 한 줄).
--   * 실패(NOT_FOUND·PARSE_FAILED·FAILED 등)는 이전 내용을 지우지 않고 실패 정보만 덧붙인다.
--   * 새 FK 에 CASCADE 없음.

CREATE TABLE staging_listings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_code        VARCHAR(30)   NOT NULL,
    platform_work_id     VARCHAR(100)  NOT NULL,
    id_scope             VARCHAR(20)   NOT NULL DEFAULT 'UNKNOWN',
    listing_kind         VARCHAR(20),
    language_code        VARCHAR(35)   NOT NULL DEFAULT 'ko',
    url                  VARCHAR(500)  NOT NULL,
    title_raw            VARCHAR(500),
    title_clean          VARCHAR(255),
    genres_raw           JSONB         NOT NULL DEFAULT '[]',
    age_rating_raw       VARCHAR(50),
    age_class            VARCHAR(10)   NOT NULL DEFAULT 'UNKNOWN',
    age_signals          JSONB         NOT NULL DEFAULT '[]',
    serial_status_raw    VARCHAR(100),
    serial_status        VARCHAR(20)   NOT NULL DEFAULT 'UNKNOWN',
    cover_url            VARCHAR(1000),
    synopsis_text        TEXT,
    synopsis_sha256      CHAR(64),
    synopsis_length      INTEGER,
    extra                JSONB         NOT NULL DEFAULT '{}',
    field_sources        JSONB         NOT NULL DEFAULT '{}',
    detail_status        VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    content_hash         CHAR(64),
    first_seen_at        TIMESTAMPTZ   NOT NULL,
    last_seen_at         TIMESTAMPTZ   NOT NULL,
    last_changed_at      TIMESTAMPTZ,
    first_run_id         BIGINT        NOT NULL,
    last_run_id          BIGINT        NOT NULL,
    last_failure_reason  VARCHAR(20),
    last_failure_at      TIMESTAMPTZ,
    last_failure_run_id  BIGINT,
    consecutive_failures INTEGER       NOT NULL DEFAULT 0,
    review_status        VARCHAR(20)   NOT NULL DEFAULT 'NEW',
    linked_listing_id    BIGINT,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_staging_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT fk_staging_first_run FOREIGN KEY (first_run_id) REFERENCES crawl_runs (id),
    CONSTRAINT fk_staging_last_run FOREIGN KEY (last_run_id) REFERENCES crawl_runs (id),
    CONSTRAINT fk_staging_failure_run FOREIGN KEY (last_failure_run_id) REFERENCES crawl_runs (id),
    CONSTRAINT fk_staging_linked_listing FOREIGN KEY (linked_listing_id) REFERENCES work_platform_listings (id),
    CONSTRAINT uk_staging_platform_work UNIQUE (platform_code, platform_work_id),
    -- V7 의 연결 규칙과 같은 값·형식
    CONSTRAINT ck_staging_platform_work_id CHECK (platform_work_id ~ '^[!-~]+$'),
    CONSTRAINT ck_staging_scope CHECK (id_scope IN ('SERIES', 'VOLUME_OR_EPISODE', 'EDITION', 'UNKNOWN')),
    CONSTRAINT ck_staging_kind CHECK (listing_kind IS NULL OR listing_kind IN ('MAIN', 'SEASON', 'EDITION', 'TRANSLATION')),
    CONSTRAINT ck_staging_url CHECK (url LIKE 'https://%'),
    CONSTRAINT ck_staging_cover_url CHECK (cover_url IS NULL OR cover_url LIKE 'https://%'),
    CONSTRAINT ck_staging_age CHECK (age_class IN ('GENERAL', 'ADULT', 'UNKNOWN')),
    CONSTRAINT ck_staging_serial CHECK (serial_status IN ('ONGOING', 'COMPLETED', 'HIATUS', 'UNKNOWN')),
    CONSTRAINT ck_staging_detail CHECK (detail_status IN
        ('PENDING', 'OK', 'GATED', 'SKIPPED_ADULT', 'NOT_FOUND', 'PARSE_FAILED', 'FAILED')),
    CONSTRAINT ck_staging_review CHECK (review_status IN
        ('NEW', 'CANDIDATES', 'IN_REVIEW', 'LINKED', 'NEW_WORK', 'REJECTED', 'ON_HOLD', 'MERGED_ALIAS')),
    CONSTRAINT ck_staging_failure CHECK (last_failure_reason IS NULL OR last_failure_reason IN
        ('GATED', 'SKIPPED_ADULT', 'NOT_FOUND', 'PARSE_FAILED', 'FAILED')),
    CONSTRAINT ck_staging_failure_pair CHECK ((last_failure_reason IS NULL) = (last_failure_at IS NULL)
        AND (last_failure_reason IS NULL) = (last_failure_run_id IS NULL)),
    CONSTRAINT ck_staging_failures CHECK (consecutive_failures >= 0
        AND (consecutive_failures = 0 OR last_failure_reason IS NOT NULL)),
    -- 소개문은 원문·해시·길이가 함께 있거나 함께 없다(NOT_COLLECTED 면 저장하지 않음)
    CONSTRAINT ck_staging_synopsis CHECK ((synopsis_text IS NULL) = (synopsis_sha256 IS NULL)
        AND (synopsis_text IS NULL) = (synopsis_length IS NULL) AND (synopsis_length IS NULL OR synopsis_length >= 0)),
    CONSTRAINT ck_staging_hashes CHECK ((synopsis_sha256 IS NULL OR synopsis_sha256 ~ '^[0-9a-f]{64}$')
        AND (content_hash IS NULL OR content_hash ~ '^[0-9a-f]{64}$')),
    CONSTRAINT ck_staging_seen CHECK (last_seen_at >= first_seen_at),
    CONSTRAINT ck_staging_json CHECK (jsonb_typeof(genres_raw) = 'array' AND jsonb_typeof(age_signals) = 'array'
        AND jsonb_typeof(extra) = 'object' AND jsonb_typeof(field_sources) = 'object'),
    CONSTRAINT ck_staging_language CHECK (btrim(language_code) <> '')
);
CREATE INDEX idx_staging_review ON staging_listings (platform_code, review_status, id);
CREATE INDEX idx_staging_last_run ON staging_listings (last_run_id);

-- 리디처럼 회차·권 ID 가 여러 개인 경우: 다른 ID 로 발견돼도 대표 행 하나로 모은다(§6.2)
CREATE TABLE staging_id_aliases (
    platform_code VARCHAR(30)  NOT NULL,
    alias_id      VARCHAR(100) NOT NULL,
    staging_id    BIGINT       NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_staging_id_aliases PRIMARY KEY (platform_code, alias_id),
    CONSTRAINT fk_staging_aliases_platform FOREIGN KEY (platform_code) REFERENCES platforms (code),
    CONSTRAINT fk_staging_aliases_staging FOREIGN KEY (staging_id) REFERENCES staging_listings (id),
    CONSTRAINT ck_staging_aliases_id CHECK (alias_id ~ '^[!-~]+$')
);
CREATE INDEX idx_staging_aliases_staging ON staging_id_aliases (staging_id);

-- 어떤 발견 경로에서 봤는지(누락 대조용)
CREATE TABLE staging_listing_discoveries (
    staging_id    BIGINT       NOT NULL,
    source_key    VARCHAR(100) NOT NULL,
    first_seen_at TIMESTAMPTZ  NOT NULL,
    last_seen_at  TIMESTAMPTZ  NOT NULL,
    last_run_id   BIGINT       NOT NULL,
    CONSTRAINT pk_staging_discoveries PRIMARY KEY (staging_id, source_key),
    CONSTRAINT fk_staging_discoveries_staging FOREIGN KEY (staging_id) REFERENCES staging_listings (id),
    CONSTRAINT fk_staging_discoveries_run FOREIGN KEY (last_run_id) REFERENCES crawl_runs (id),
    CONSTRAINT ck_staging_discoveries_key CHECK (source_key ~ '^[a-z0-9][a-z0-9:_.-]{0,99}$'),
    CONSTRAINT ck_staging_discoveries_seen CHECK (last_seen_at >= first_seen_at)
);

-- 수집한 크레딧(원문 보존). UNSPECIFIED 는 staging 에만 있다(works 크레딧은 세 역할만)
CREATE TABLE staging_credits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staging_id          BIGINT       NOT NULL,
    name_raw            VARCHAR(200) NOT NULL,
    role_raw            VARCHAR(50),
    role                VARCHAR(20)  NOT NULL,
    platform_creator_id VARCHAR(100),
    position            SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT fk_staging_credits_staging FOREIGN KEY (staging_id) REFERENCES staging_listings (id),
    CONSTRAINT uk_staging_credits UNIQUE (staging_id, name_raw, role),
    CONSTRAINT ck_staging_credits_role CHECK (role IN ('STORY', 'ART', 'ORIGINAL_STORY', 'UNSPECIFIED')),
    CONSTRAINT ck_staging_credits_name CHECK (btrim(name_raw) <> ''),
    CONSTRAINT ck_staging_credits_position CHECK (position >= 0)
);

-- 바뀐 필드의 이전·이후 값(소개문은 해시만). staging 갱신과 같은 트랜잭션, 실행당 한 줄(재개해도 늘지 않음)
CREATE TABLE staging_listing_changes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staging_id     BIGINT      NOT NULL,
    run_id         BIGINT      NOT NULL,
    changed_fields JSONB       NOT NULL,
    changed_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_staging_changes_staging FOREIGN KEY (staging_id) REFERENCES staging_listings (id),
    CONSTRAINT fk_staging_changes_run FOREIGN KEY (run_id) REFERENCES crawl_runs (id),
    CONSTRAINT uk_staging_changes_run UNIQUE (staging_id, run_id),
    CONSTRAINT ck_staging_changes_fields CHECK (jsonb_typeof(changed_fields) = 'object' AND changed_fields <> '{}')
);
